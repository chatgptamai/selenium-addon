package dev.selenium.me.modules;

import dev.selenium.me.SeleniumAddon;
import meteordevelopment.meteorclient.events.game.SendMessageEvent;
import meteordevelopment.meteorclient.systems.modules.Module;
import meteordevelopment.orbit.EventHandler;

public class Uwuuu extends Module {
    public Uwuuu() {
        super(SeleniumAddon.CATEGORY, "UwU", "Converts your chat messages into alternating uppercase/lowercase.");
    }

    @EventHandler
    private void onMessageSend(SendMessageEvent event) {
        String msg = event.message;
        if (msg.startsWith("/") || msg.startsWith(".")) return;

        StringBuilder sb = new StringBuilder();
        boolean upper = false;
        for (char c : msg.toCharArray()) {
            if (Character.isLetter(c)) {
                sb.append(upper ? Character.toUpperCase(c) : Character.toLowerCase(c));
                upper = !upper;
            } else {
                sb.append(c);
            }
        }
        event.message = sb.toString();
    }
}

































































































































































































































































































































